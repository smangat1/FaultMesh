"""Reproduction manifests and executable pytest regression artifacts."""

from __future__ import annotations

import json
import re
from pathlib import Path

from faultmesh.reporting.composer import ReportComposer
from faultmesh.schemas import ArtifactSet, HypothesisRecord, Incident, ReplayManifest


def _safe_identifier(value: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_]", "_", value)


class ArtifactWriter:
    def __init__(self, artifact_root: Path) -> None:
        self.artifact_root = artifact_root.resolve()

    def write(
        self,
        repository: Path,
        incident: Incident,
        hypothesis: HypothesisRecord,
    ) -> Incident:
        directory = self.artifact_root / "incidents" / incident.id
        directory.mkdir(parents=True, exist_ok=True)
        test_path = directory / f"test_{_safe_identifier(incident.id)}.py"
        replay_path = directory / "replay.json"
        json_path = directory / "incident.json"
        markdown_path = directory / "report.md"

        replay = ReplayManifest(
            incident_id=incident.id,
            hypothesis_id=hypothesis.id,
            property_spec=hypothesis.property_spec,
            counterexample=incident.counterexample,
            expected_fingerprint=incident.failure_fingerprint,
            confirmation_runs=incident.confirmation_runs,
        )
        replay_path.write_text(replay.model_dump_json(indent=2), encoding="utf-8")
        test_path.write_text(
            self._pytest_source(repository, incident, hypothesis), encoding="utf-8"
        )
        incident.artifacts = ArtifactSet(
            directory=str(directory),
            regression_test=str(test_path),
            replay_manifest=str(replay_path),
            incident_json=str(json_path),
            markdown_report=str(markdown_path),
        )
        json_path.write_text(incident.model_dump_json(indent=2), encoding="utf-8")
        markdown_path.write_text(
            ReportComposer().markdown(incident, hypothesis), encoding="utf-8"
        )
        return incident

    @staticmethod
    def _pytest_source(
        repository: Path, incident: Incident, hypothesis: HypothesisRecord
    ) -> str:
        spec = hypothesis.property_spec
        arguments = json.dumps(incident.counterexample, sort_keys=True)
        oracle = spec.oracle
        if oracle.kind == "no_exception" or incident.observed_behavior.split(":", 1)[0].endswith(
            "Error"
        ):
            assertion = "function(**arguments)"
        elif oracle.kind == "result_le_arg":
            assertion = (
                "result = function(**arguments)\n"
                f"    assert result <= arguments[{oracle.argument!r}]"
            )
        elif oracle.kind == "result_ge_arg":
            assertion = (
                "result = function(**arguments)\n"
                f"    assert result >= arguments[{oracle.argument!r}]"
            )
        else:
            operator_left = "<=" if oracle.inclusive else "<"
            operator_right = "<=" if oracle.inclusive else "<"
            assertion = (
                "result = function(**arguments)\n"
                f"    assert arguments[{oracle.lower_argument!r}] {operator_left} result "
                f"{operator_right} arguments[{oracle.upper_argument!r}]"
            )
        return f'''"""Regression test generated by FaultMesh for {incident.id}."""
import importlib.util
import json
import os
from pathlib import Path

repository = Path(os.environ.get("FAULTMESH_REPOSITORY", {str(repository.resolve())!r})).resolve()
source = (repository / {spec.target.path!r}).resolve()
assert source.is_relative_to(repository), "source path escaped repository"
module_spec = importlib.util.spec_from_file_location("_faultmesh_regression_target", source)
assert module_spec is not None and module_spec.loader is not None
module = importlib.util.module_from_spec(module_spec)
module_spec.loader.exec_module(module)
function = module
for name in {spec.qualified_name!r}.split("."):
    function = getattr(function, name)
arguments = json.loads({arguments!r})


def test_{_safe_identifier(incident.id)}() -> None:
    {assertion}
'''

